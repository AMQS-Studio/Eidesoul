@pytest.fixture(autouse=True)
def _database_url(monkeypatch: pytest.MonkeyPatch) -> None:
    """Host-file validation needs a URL, and no test may reach a real deployment database."""
    monkeypatch.setenv("MONOAGENS_DATABASE_URL", support.test_dsn())
    monkeypatch.delenv("MONOAGENS_STACK", raising=False)


def deployment(folder: Path, *, gateways: tuple[str, ...] = ()) -> Path:
    """A complete host directory, generated by the same code `monoagens init` uses."""
    contents = init.build(
        provider="openai",
        language="en",
        locale="en-US",
        timezone="UTC",
        gateways=gateways,
    )
    for name, body in contents.items():
        path = folder / name
        path.write_text(body, encoding="utf-8")
        path.chmod(0o600 if name in {".env", "roles.yaml"} else 0o644)
    return folder / "config.yaml"


# ------------------------------------------------------------------ gateway


def test_gateway_enable_disable_delete_keep_comments(tmp_path, monkeypatch):
    cfg = deployment(tmp_path)
    cfg.write_text(cfg.read_text(encoding="utf-8") + "# operator note\n", encoding="utf-8")
    roles = tmp_path / "roles.yaml"
    roles.write_text("# roles note\n" + roles.read_text(encoding="utf-8"), encoding="utf-8")
    monkeypatch.setattr(gateway, "SESSIONS", tmp_path / "sessions")

    assert gateway.set_enabled(str(cfg), "whatsapp", True) == 0
    text = cfg.read_text(encoding="utf-8")
    assert "# operator note" in text
    assert yaml.safe_load(text)["gateways"]["whatsapp"]["enabled"] is True
    body = yaml.safe_load(roles.read_text(encoding="utf-8"))["roles"]
    assert body["administrator"]["gateways"]["whatsapp"]["dm"] is True
    assert body["guest"]["gateways"]["whatsapp"]["groups"] == "none"
    assert "# roles note" in roles.read_text(encoding="utf-8")

    assert gateway.set_enabled(str(cfg), "whatsapp", False) == 0
    body = yaml.safe_load(cfg.read_text(encoding="utf-8"))
    assert body["gateways"]["whatsapp"]["enabled"] is False

    (tmp_path / "sessions" / "whatsapp").mkdir(parents=True)
    # A legacy file written by PyYAML uses indentless sequences; the writer must still cope.
    roles.write_text(
        yaml.safe_dump(yaml.safe_load(roles.read_text(encoding="utf-8")), sort_keys=False),
        encoding="utf-8",
    )
    assert gateway.delete(str(cfg), "whatsapp") == 0
    assert "whatsapp" not in yaml.safe_load(cfg.read_text(encoding="utf-8"))["gateways"]
    blocks = yaml.safe_load(roles.read_text(encoding="utf-8"))["roles"]
    assert all("whatsapp" not in (item.get("gateways") or {}) for item in blocks.values())
    assert blocks["administrator"]["tools"] == ["*"]
    assert not (tmp_path / "sessions" / "whatsapp").exists()


