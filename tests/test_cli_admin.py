def test_logs_filter_lines_by_level(tmp_path, capsys):
    cfg = deployment(tmp_path)
    current = service.load(str(cfg))
    log_path = current.log_file()
    log_path.parent.mkdir(parents=True, exist_ok=True)
    log_path.write_text(
        "\n".join(
            (
                "2026-01-01T00:00:00Z DEBUG detail",
                "2026-01-01T00:00:01Z INFO routine",
                "2026-01-01T00:00:02Z WARNING careful",
                "2026-01-01T00:00:03Z ERROR failed",
                "continuation without a level",
            )
        )
        + "\n",
        encoding="utf-8",
    )

    assert service.logs(current, minimum="WARNING") == 0
    out = capsys.readouterr().out
    assert "careful" in out
    assert "failed" in out
    assert "continuation without a level" in out
    assert "detail" not in out
    assert "routine" not in out
    assert service.filter_lines(["x DEBUG y"], "INFO") == []


